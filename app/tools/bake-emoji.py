#   tools/bake-emoji.py emoji-test.txt twemoji/assets/72x72 assets/art/emoji.png src/discord/emoji_table.inc
#
# emoji-test.txt is Unicode's list (15.1, https://unicode.org/Public/emoji/15.1/emoji-test.txt);
# the pictures are Twemoji 15.1.0 (jdecked/twemoji, CC-BY 4.0, as Discord draws them). Every
# fully-qualified emoji without a skin tone goes in, in Unicode's order, one 48 px cell each.
# Skin tones and anything else not baked load from the Twemoji CDN at run time.
import sys
from pathlib import Path

from PIL import Image

CELL = 48
COLUMNS = 40
SKIN = range(0x1F3FB, 0x1F400)


def file_name(points):
    # As screens/chat.cpp emoji_url: FE0F is left out unless a ZWJ joins the sequence.
    keep = 0x200D in points
    return "-".join(f"{p:x}" for p in points if keep or p != 0xFE0F)


def c_string(text):
    return '"' + "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else
                         "".join(f"\\{b:03o}" for b in c.encode()) for c in text) + '"'


def main(test_txt, pictures, out_png, out_inc):
    groups, rows = [], []
    for line in Path(test_txt).read_text(encoding="utf-8").splitlines():
        if line.startswith("# group: "):
            groups.append(line[9:].strip())
            continue
        if not line or line.startswith("#") or "; fully-qualified" not in line:
            continue
        if groups[-1] == "Component":
            continue
        points = [int(p, 16) for p in line.split(";")[0].split()]
        if any(p in SKIN for p in points):
            continue
        name = line.split("#", 1)[1].strip().split(" ", 2)[2]  # "😀 E1.0 grinning face"
        picture = Path(pictures) / (file_name(points) + ".png")
        if not picture.exists():
            print("no picture:", name, file=sys.stderr)
            continue
        rows.append((len(groups) - 1, "".join(chr(p) for p in points), name, picture))

    lines = (len(rows) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * CELL, lines * CELL), (0, 0, 0, 0))
    for i, (_, _, _, picture) in enumerate(rows):
        cell = Image.open(picture).convert("RGBA").resize((CELL, CELL), Image.LANCZOS)
        atlas.paste(cell, ((i % COLUMNS) * CELL, (i // COLUMNS) * CELL))
    atlas.save(out_png, optimize=True)

    used = sorted({g for g, _, _, _ in rows})
    with open(out_inc, "w", encoding="ascii") as out:
        out.write("// Generated by tools/bake-emoji.py from Unicode emoji-test.txt 15.1 and Twemoji 15.1.0.\n")
        out.write(f"// {len(rows)} emoji in assets/art/emoji.png, {COLUMNS} to a row of {CELL} px cells.\n")
        out.write(f"constexpr int kEmojiColumns = {COLUMNS};\nconstexpr int kEmojiCell = {CELL};\n")
        out.write("constexpr const char *kEmojiGroups[] = {" + ", ".join(c_string(groups[g]) for g in used) + "};\n")
        out.write("constexpr EmojiEntry kEmojiTable[] = {\n")
        for g, text, name, _ in rows:
            out.write(f"    {{{used.index(g)}, {c_string(text)}, {c_string(name)}}},\n")
        out.write("};\n")
    print(f"{len(rows)} emoji, atlas {atlas.size[0]}x{atlas.size[1]}")


if __name__ == "__main__":
    main(*sys.argv[1:5])
