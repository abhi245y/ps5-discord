#!/usr/bin/env python3
# Embeds a PEM root store as a NUL-terminated C array (mbedtls_x509_crt_parse wants the NUL).
# usage: embed_ca.py <ca-bundle.pem> <out.c>
import sys

pem = open(sys.argv[1], "rb").read() + b"\0"
with open(sys.argv[2], "w") as out:
    out.write("// generated by tools/embed_ca.py, do not edit\n#include <stddef.h>\n")
    out.write("const unsigned char ca_bundle_pem[] = {\n")
    for i in range(0, len(pem), 16):
        out.write("".join(f"{b},"for b in pem[i:i + 16]) + "\n")
    out.write("};\nconst size_t ca_bundle_pem_len = sizeof(ca_bundle_pem);\n")
