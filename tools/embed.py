#!/usr/bin/env python3
# Embeds a file as a NUL-terminated C byte array plus its length (NUL included).
# usage: embed.py <input> <out.c> <symbol>
import sys

data = open(sys.argv[1], "rb").read() + b"\0"
sym = sys.argv[3]
with open(sys.argv[2], "w") as out:
    out.write("// generated by tools/embed.py, do not edit\n#include <stddef.h>\n")
    out.write(f"const unsigned char {sym}[] = {{\n")
    for i in range(0, len(data), 16):
        out.write("".join(f"{b}," for b in data[i:i + 16]) + "\n")
    out.write(f"}};\nconst size_t {sym}_len = sizeof({sym});\n")
